-- Reserva ATÔMICA de uma pergunta: incrementa e checa o limite na MESMA
-- instrução (INSERT ... ON CONFLICT DO UPDATE ... WHERE usadas < limite). Duas
-- abas perguntando ao mesmo tempo serializam no lock da linha e a segunda
-- reavalia o WHERE com o valor já incrementado — não há como passar do limite.
CREATE OR REPLACE FUNCTION public.darcy_reservar_pergunta(p_user_id uuid, p_limite_padrao integer)
 RETURNS TABLE(permitido boolean, usadas integer, limite integer, dia date, renova_em timestamptz)
 LANGUAGE plpgsql
 VOLATILE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
#variable_conflict use_column
DECLARE
  v_dia    date := public.darcy_dia_brasilia(now());
  v_limite integer;
  v_usadas integer;
BEGIN
  IF p_user_id IS NULL THEN
    RAISE EXCEPTION 'p_user_id é obrigatório';
  END IF;

  v_limite := public.darcy_limite_efetivo(p_user_id, v_dia, p_limite_padrao);

  IF v_limite > 0 THEN
    INSERT INTO public.darcy_uso_diario AS u (user_id, dia, usadas, limite)
    VALUES (p_user_id, v_dia, 1, v_limite)
    ON CONFLICT ON CONSTRAINT darcy_uso_diario_pkey DO UPDATE
       SET usadas = u.usadas + 1, limite = v_limite, atualizado_em = now()
     WHERE u.usadas < v_limite
    RETURNING u.usadas INTO v_usadas;
  END IF;

  IF v_usadas IS NOT NULL THEN
    RETURN QUERY SELECT true, v_usadas, v_limite, v_dia, public.darcy_renova_em(v_dia);
    RETURN;
  END IF;

  SELECT u.usadas INTO v_usadas
    FROM public.darcy_uso_diario u
   WHERE u.user_id = p_user_id AND u.dia = v_dia;

  RETURN QUERY SELECT false, COALESCE(v_usadas, 0), v_limite, v_dia, public.darcy_renova_em(v_dia);
END;
$function$;

-- Estorno: a IA falhou, a pergunta não conta. Recebe o dia da RESERVA (uma
-- pergunta feita às 23:59 que falha depois da meia-noite estorna o dia certo).
CREATE OR REPLACE FUNCTION public.darcy_estornar_pergunta(p_user_id uuid, p_dia date)
 RETURNS integer
 LANGUAGE sql
 VOLATILE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  UPDATE public.darcy_uso_diario u
     SET usadas = u.usadas - 1, atualizado_em = now()
   WHERE u.user_id = p_user_id AND u.dia = p_dia AND u.usadas > 0
  RETURNING u.usadas;
$function$;

-- Estado da cota sem consumir (rodinha ao abrir a página).
CREATE OR REPLACE FUNCTION public.darcy_estado_cota(p_user_id uuid, p_limite_padrao integer)
 RETURNS TABLE(usadas integer, limite integer, dia date, renova_em timestamptz)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT COALESCE((SELECT u.usadas FROM public.darcy_uso_diario u
                    WHERE u.user_id = p_user_id AND u.dia = d.dia), 0),
         public.darcy_limite_efetivo(p_user_id, d.dia, p_limite_padrao),
         d.dia,
         public.darcy_renova_em(d.dia)
    FROM (SELECT public.darcy_dia_brasilia(now()) AS dia) d;
$function$;

-- Custo de IA do dia corrente (Brasília), mesmo cálculo do dashboard.
CREATE OR REPLACE FUNCTION public.darcy_custo_ia_hoje()
 RETURNS numeric
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT COALESCE(round(sum(
           (l.prompt_tokens / 1000.0) * COALESCE(p.input_per_1k, 0)
         + (l.completion_tokens / 1000.0) * COALESCE(p.output_per_1k, 0)
         )::numeric, 4), 0)
    FROM public.ai_usage_log l
    LEFT JOIN public.ai_pricing p ON p.model = l.model
   WHERE l.created_at >= (public.darcy_dia_brasilia(now())::timestamp AT TIME ZONE 'America/Sao_Paulo');
$function$;

