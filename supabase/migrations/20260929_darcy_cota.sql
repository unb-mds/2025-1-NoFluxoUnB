-- Mensagem do suporte no ticket, com o mesmo efeito de "primeira resposta" de
-- ticket_add_message (sem o rate limit de 3s, que travaria a ação logo depois
-- de o admin ter escrito na conversa).
CREATE OR REPLACE FUNCTION public.darcy_responder_ticket(p_ticket_id bigint, p_texto text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.ticket_messages m
                  WHERE m.ticket_id = p_ticket_id AND m.author_role = 'tech') THEN
    INSERT INTO public.ticket_audit_log (ticket_id, actor_id, action, notes)
    VALUES (p_ticket_id, auth.uid(), 'message_added', 'Primeira resposta do suporte');
  END IF;

  INSERT INTO public.ticket_messages (ticket_id, author_id, author_role, content)
  VALUES (p_ticket_id, auth.uid(), 'tech', left(btrim(p_texto), 2000));
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.darcy_responder_ticket(bigint, text) FROM PUBLIC, anon, authenticated;

-- p_opcao: 'hoje'   → +p_quantidade só hoje;
--          'semana' → +p_quantidade por dia, de hoje até hoje+6;
--          'limite' → limite diário passa a p_quantidade, sem data de fim.
CREATE OR REPLACE FUNCTION public.darcy_aprovar_pedido(
  p_ticket_id  bigint,
  p_opcao      text,
  p_quantidade integer,
  p_resposta   text DEFAULT NULL
)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_ticket    public.tickets;
  v_hoje      date := public.darcy_dia_brasilia(now());
  v_tipo      text;
  v_ate       date;
  v_concessao public.darcy_cota_concessoes;
  v_texto     text;
BEGIN
  IF NOT public.is_ticket_admin() THEN
    RAISE EXCEPTION 'forbidden: admin role required';
  END IF;

  IF p_opcao NOT IN ('hoje', 'semana', 'limite') THEN
    RAISE EXCEPTION 'opção inválida: %', p_opcao;
  END IF;
  IF p_quantidade IS NULL OR p_quantidade < 1 OR p_quantidade > 1000 THEN
    RAISE EXCEPTION 'quantidade inválida: %', p_quantidade;
  END IF;

  SELECT t.* INTO v_ticket FROM public.tickets t WHERE t.id = p_ticket_id FOR UPDATE;
  IF v_ticket.id IS NULL THEN
    RAISE EXCEPTION 'ticket not found: %', p_ticket_id;
  END IF;
  IF COALESCE(v_ticket.metadata->>'tipo', '') <> 'darcy_mais_perguntas' THEN
    RAISE EXCEPTION 'Este chamado não é um pedido de mais perguntas no Darcy.';
  END IF;
  IF v_ticket.status = 'resolvido' THEN
    RAISE EXCEPTION 'Este chamado já foi resolvido.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.darcy_cota_concessoes c WHERE c.ticket_id = p_ticket_id) THEN
    RAISE EXCEPTION 'Este pedido já foi aprovado.';
  END IF;

  IF p_opcao = 'limite' THEN
    v_tipo := 'limite'; v_ate := NULL;
  ELSIF p_opcao = 'semana' THEN
    v_tipo := 'extra'; v_ate := v_hoje + 6;
  ELSE
    v_tipo := 'extra'; v_ate := v_hoje;
  END IF;

  INSERT INTO public.darcy_cota_concessoes
    (user_id, tipo, quantidade, valida_de, valida_ate, motivo, ticket_id, aprovado_por)
  VALUES
    (v_ticket.created_by, v_tipo, p_quantidade, v_hoje, v_ate,
     left(COALESCE(v_ticket.metadata->>'motivo', v_ticket.description), 500),
     p_ticket_id, auth.uid())
  RETURNING * INTO v_concessao;

  v_texto := COALESCE(NULLIF(btrim(p_resposta), ''),
    CASE p_opcao
      WHEN 'hoje'   THEN format('Pedido aprovado! Você ganhou +%s perguntas no Darcy hoje.', p_quantidade)
      WHEN 'semana' THEN format('Pedido aprovado! Você ganhou +%s perguntas por dia no Darcy até %s.',
                                p_quantidade, to_char(v_ate, 'DD/MM'))
      ELSE format('Pedido aprovado! Seu limite no Darcy passou para %s perguntas por dia.', p_quantidade)
    END);
  PERFORM public.darcy_responder_ticket(p_ticket_id, v_texto);

  UPDATE public.tickets SET status = 'resolvido' WHERE id = p_ticket_id;

  RETURN to_jsonb(v_concessao);
END;
$function$;

CREATE OR REPLACE FUNCTION public.darcy_recusar_pedido(p_ticket_id bigint, p_resposta text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_ticket public.tickets;
BEGIN
  IF NOT public.is_ticket_admin() THEN
    RAISE EXCEPTION 'forbidden: admin role required';
  END IF;
  IF p_resposta IS NULL OR btrim(p_resposta) = '' THEN
    RAISE EXCEPTION 'Explique ao aluno o motivo da recusa.';
  END IF;

  SELECT t.* INTO v_ticket FROM public.tickets t WHERE t.id = p_ticket_id FOR UPDATE;
  IF v_ticket.id IS NULL THEN
    RAISE EXCEPTION 'ticket not found: %', p_ticket_id;
  END IF;
  IF COALESCE(v_ticket.metadata->>'tipo', '') <> 'darcy_mais_perguntas' THEN
    RAISE EXCEPTION 'Este chamado não é um pedido de mais perguntas no Darcy.';
  END IF;
  IF v_ticket.status = 'resolvido' THEN
    RAISE EXCEPTION 'Este chamado já foi resolvido.';
  END IF;

  PERFORM public.darcy_responder_ticket(p_ticket_id, p_resposta);
  UPDATE public.tickets SET status = 'resolvido' WHERE id = p_ticket_id;
END;
$function$;

