-- 7. Pedido de mais perguntas (ticket de suporte) — ações do admin
--    O ticket é criado pelo aluno no sistema de suporte existente com
--    metadata.tipo = 'darcy_mais_perguntas'. Aprovar cria a concessão vinculada
--    ao ticket, responde na conversa e resolve o ticket, tudo numa transação.
