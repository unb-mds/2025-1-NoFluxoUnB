-- Dia corrente (ou de p_em) no fuso de Brasília.
CREATE OR REPLACE FUNCTION public.darcy_dia_brasilia(p_em timestamptz DEFAULT now())
 RETURNS date
 LANGUAGE sql
 STABLE
AS $function$
  SELECT (p_em AT TIME ZONE 'America/Sao_Paulo')::date;
$function$;

-- Meia-noite de Brasília que encerra o dia p_dia.
CREATE OR REPLACE FUNCTION public.darcy_renova_em(p_dia date)
 RETURNS timestamptz
 LANGUAGE sql
 STABLE
AS $function$
  SELECT ((p_dia + 1)::timestamp AT TIME ZONE 'America/Sao_Paulo');
$function$;

-- Limite do dia = max(padrão, maior 'limite' vigente) + soma dos 'extra' vigentes.
CREATE OR REPLACE FUNCTION public.darcy_limite_efetivo(p_user_id uuid, p_dia date, p_limite_padrao integer)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT GREATEST(
           GREATEST(COALESCE(p_limite_padrao, 0), 0),
           COALESCE((SELECT max(c.quantidade) FROM public.darcy_cota_concessoes c
                      WHERE c.user_id = p_user_id AND c.tipo = 'limite'
                        AND c.valida_de <= p_dia
                        AND (c.valida_ate IS NULL OR c.valida_ate >= p_dia)), 0)
         )
       + COALESCE((SELECT sum(c.quantidade)::integer FROM public.darcy_cota_concessoes c
                    WHERE c.user_id = p_user_id AND c.tipo = 'extra'
                      AND c.valida_de <= p_dia AND c.valida_ate >= p_dia), 0);
$function$;

