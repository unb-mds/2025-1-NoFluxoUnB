-- Mesma assinatura e chaves de antes, com três mudanças:
--   * por_dia agrupa pelo dia de Brasília (antes era o dia UTC: o que acontecia
--     depois das 21h caía no dia seguinte);
--   * total_perguntas: uma pergunta = mesmo pergunta_id, ou, nas linhas antigas
--     sem pergunta_id, mesmo (endpoint, created_at) — só nos endpoints que são
--     pergunta do aluno (chat/analyze). Linha sem pergunta_id de ferramenta
--     interna (buscar-materias, dificuldade do plano) entra no custo e em
--     total_requisicoes mas não é pergunta. As linhas antigas são aproximadas:
--     antes do pergunta_id, cada chamada ao modelo com horário próprio vira uma;
--   * por_endpoint, custo_hoje e sem_tokens (linhas sem tokens, que não custam).
CREATE OR REPLACE FUNCTION public.get_ai_cost_metrics(p_days integer DEFAULT 30)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_moeda        text;
  v_total_req    bigint;
  v_total_tokens bigint;
  v_custo_total  numeric;
  v_por_modelo   jsonb;
  v_por_dia      jsonb;
  v_por_endpoint jsonb;
  v_perguntas    bigint;
  v_sem_tokens   bigint;
  v_sem_preco    boolean;
BEGIN
  IF NOT public.has_admin_scope('dashboard') THEN
    RAISE EXCEPTION 'forbidden: dashboard scope required';
  END IF;

  SELECT COALESCE(max(currency), 'BRL') INTO v_moeda FROM public.ai_pricing;

  WITH r AS (
    SELECT l.endpoint, l.model, l.total_tokens, l.created_at,
           CASE
             WHEN l.pergunta_id IS NOT NULL THEN l.pergunta_id::text
             WHEN l.endpoint IN ('assistente-chat', 'planejamento-chat', 'chat-send',
                                 'analyze-sabia', 'analyze-sabia-stream')
               THEN l.endpoint || '|' || l.created_at::text
           END AS pergunta,  -- NULL = não é pergunta (count DISTINCT ignora)
           (l.prompt_tokens / 1000.0) * COALESCE(p.input_per_1k, 0)
         + (l.completion_tokens / 1000.0) * COALESCE(p.output_per_1k, 0) AS custo
      FROM public.ai_usage_log l
      LEFT JOIN public.ai_pricing p ON p.model = l.model
     WHERE l.created_at >= now() - (p_days || ' days')::interval
  )
  SELECT
    (SELECT count(*) FROM r),
    (SELECT COALESCE(sum(total_tokens), 0) FROM r),
    (SELECT COALESCE(round(sum(custo)::numeric, 4), 0) FROM r),
    (SELECT COALESCE(jsonb_object_agg(model, jsonb_build_object(
              'requisicoes', req, 'tokens', tok, 'custo', round(custo::numeric, 4)
            )) FILTER (WHERE model IS NOT NULL), '{}'::jsonb)
       FROM (SELECT model, count(*) AS req, sum(total_tokens) AS tok, sum(custo) AS custo
               FROM r GROUP BY model) m),
    (SELECT COALESCE(jsonb_agg(jsonb_build_object(
              'dia', d, 'custo', c, 'requisicoes', q_req, 'perguntas', q) ORDER BY d), '[]'::jsonb)
       FROM (SELECT (created_at AT TIME ZONE 'America/Sao_Paulo')::date AS d,
                    round(sum(custo)::numeric, 4) AS c,
                    count(*) AS q_req,
                    count(DISTINCT pergunta) AS q
               FROM r GROUP BY 1) s),
    (SELECT COALESCE(jsonb_object_agg(ep, jsonb_build_object(
              'requisicoes', q_req, 'perguntas', q, 'custo', round(c::numeric, 4))), '{}'::jsonb)
       FROM (SELECT COALESCE(endpoint, 'desconhecido') AS ep, count(*) AS q_req, sum(custo) AS c,
                    count(DISTINCT pergunta) AS q
               FROM r GROUP BY 1) e),
    (SELECT count(DISTINCT pergunta) FROM r),
    (SELECT count(*) FROM r WHERE total_tokens = 0)
  INTO v_total_req, v_total_tokens, v_custo_total, v_por_modelo, v_por_dia,
       v_por_endpoint, v_perguntas, v_sem_tokens;

  SELECT bool_or(input_per_1k = 0 AND output_per_1k = 0) INTO v_sem_preco
    FROM public.ai_pricing;

  RETURN jsonb_build_object(
    'moeda',                 v_moeda,
    'total_requisicoes',     COALESCE(v_total_req, 0),
    'total_perguntas',       COALESCE(v_perguntas, 0),
    'total_tokens',          COALESCE(v_total_tokens, 0),
    'custo_total',           COALESCE(v_custo_total, 0),
    'custo_hoje',            public.darcy_custo_ia_hoje(),
    'tokens_medios_por_req', CASE WHEN COALESCE(v_total_req, 0) > 0
                               THEN round(v_total_tokens::numeric / v_total_req, 0)
                               ELSE 0 END,
    'requisicoes_sem_tokens', COALESCE(v_sem_tokens, 0),
    'por_modelo',            COALESCE(v_por_modelo, '{}'::jsonb),
    'por_endpoint',          COALESCE(v_por_endpoint, '{}'::jsonb),
    'por_dia',               COALESCE(v_por_dia, '[]'::jsonb),
    'precos_nao_configurados', COALESCE(v_sem_preco, true)
  );
END;
$function$;

-- Uso das cotas do Darcy hoje (dia de Brasília).
CREATE OR REPLACE FUNCTION public.get_darcy_uso_metrics()
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_hoje date := public.darcy_dia_brasilia(now());
  v_res  jsonb;
BEGIN
  IF NOT public.has_admin_scope('dashboard') THEN
    RAISE EXCEPTION 'forbidden: dashboard scope required';
  END IF;

  SELECT jsonb_build_object(
    'dia',                  v_hoje,
    'perguntas_hoje',       COALESCE((SELECT sum(u.usadas) FROM public.darcy_uso_diario u WHERE u.dia = v_hoje), 0),
    'usuarios_hoje',        (SELECT count(*) FROM public.darcy_uso_diario u WHERE u.dia = v_hoje AND u.usadas > 0),
    'usuarios_no_limite',   (SELECT count(*) FROM public.darcy_uso_diario u
                              WHERE u.dia = v_hoje AND u.limite > 0 AND u.usadas >= u.limite),
    'custo_hoje',           public.darcy_custo_ia_hoje(),
    'concessoes_vigentes',  (SELECT count(*) FROM public.darcy_cota_concessoes c
                              WHERE c.valida_de <= v_hoje AND (c.valida_ate IS NULL OR c.valida_ate >= v_hoje)),
    'pedidos_pendentes',    (SELECT count(*) FROM public.tickets t
                              WHERE t.metadata->>'tipo' = 'darcy_mais_perguntas' AND t.status <> 'resolvido'),
    'top_usuarios',         COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
               'nome', x.nome_completo, 'email', x.email, 'usadas', x.usadas, 'limite', x.limite)
             ORDER BY x.usadas DESC)
        FROM (SELECT u.usadas, u.limite, us.nome_completo, us.email
                FROM public.darcy_uso_diario u
                LEFT JOIN public.users us ON us.auth_id = u.user_id
               WHERE u.dia = v_hoje AND u.usadas > 0
               ORDER BY u.usadas DESC
               LIMIT 5) x), '[]'::jsonb)
  ) INTO v_res;

  RETURN v_res;
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.get_darcy_uso_metrics() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_darcy_uso_metrics() TO authenticated;

COMMIT;
